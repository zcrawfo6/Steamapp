create table if not exists public.games (
  app_id bigint primary key,
  name text not null,
  release_date date,
  owners_min bigint,
  owners_max bigint,
  peak_ccu integer,
  required_age integer,
  price numeric(8,2),
  discount integer,
  dlc_count integer,
  windows boolean,
  mac boolean,
  linux boolean,
  metacritic_score integer,
  positive integer,
  negative integer,
  achievements integer,
  recommendations integer,
  avg_playtime_forever integer,
  median_playtime_forever integer,
  developers text,
  publishers text,
  genres text,
  primary_genre text,
  tags text
);
